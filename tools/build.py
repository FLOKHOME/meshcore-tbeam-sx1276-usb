#!/usr/bin/env python3
"""Reproducible, non-destructive MeshCore USB companion firmware builder.

This project is not affiliated with the MeshCore maintainers.
"""
from __future__ import annotations

import argparse
import hashlib
import importlib.util
import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys
from datetime import datetime, timezone

UPSTREAM_URL = "https://github.com/meshcore-dev/MeshCore.git"
DEFAULT_REF = "companion-v1.18.0"
TESTED_COMMIT_PREFIX = "81dbae5"
ENVIRONMENT = "Tbeam_SX1276_companion_radio_usb"
MARKER = "; Generated by meshcore-tbeam-sx1276-usb/tools/build.py; do not edit."
PROJECT_DIR = Path(__file__).resolve().parent.parent

# Keep this aligned with the V1.18.0 profile that was compiled and tested.
OVERLAY = f"""{MARKER}
; USB serial interface on the classic ESP32 T-Beam with SX1276.
; Inherits sources and dependencies from the upstream BLE companion,
; but deliberately excludes BLE_PIN_CODE (no Bluetooth in this build).
[env:{ENVIRONMENT}]
extends = env:Tbeam_SX1276_companion_radio_ble
build_flags =
  ${{LilyGo_TBeam_SX1276.build_flags}}
  -I examples/companion_radio/ui-new
  -D MAX_CONTACTS=160
  -D MAX_GROUP_CHANNELS=40
  -D OFFLINE_QUEUE_SIZE=128
  -D ENABLE_USB_INTERFACE
"""


def run(*argv: str, cwd: Path | None = None) -> None:
    print("+", " ".join(map(str, argv)), flush=True)
    subprocess.run([str(x) for x in argv], cwd=cwd, check=True)


def output(*argv: str, cwd: Path | None = None) -> str:
    return subprocess.check_output([str(x) for x in argv], cwd=cwd, text=True).strip()


def safe_ref(ref: str) -> str:
    # Prevent injecting git options, path separators, or shell metacharacters.
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9._-]{0,79}", ref) or ".." in ref:
        raise ValueError("Invalid --ref. Use a tag like companion-v1.18.0.")
    return ref


def validate_upstream(repo: Path) -> None:
    main_ini = repo / "platformio.ini"
    variant_ini = repo / "variants/lilygo_tbeam_SX1276/platformio.ini"
    companion_cpp = repo / "examples/companion_radio/main.cpp"
    for file in (main_ini, variant_ini, companion_cpp):
        if not file.is_file():
            raise RuntimeError(f"Upstream source structure changed; missing: {file}")
    root_config = main_ini.read_text(encoding="utf-8")
    variant_config = variant_ini.read_text(encoding="utf-8")
    main_code = companion_cpp.read_text(encoding="utf-8")
    if "platformio.local.ini" not in root_config or "variants/*/platformio.ini" not in root_config:
        raise RuntimeError("Upstream does not load platformio.local.ini; refusing to patch source.")
    if "[env:Tbeam_SX1276_companion_radio_ble]" not in variant_config:
        raise RuntimeError("Upstream no longer provides the T-Beam SX1276 BLE base profile.")
    if "[env:Tbeam_SX1276_companion_radio_usb]" in variant_config:
        raise RuntimeError("Upstream already has a T-Beam USB profile. Check the official option first.")
    if "ENABLE_USB_INTERFACE" not in main_code:
        raise RuntimeError("The companion source no longer defines ENABLE_USB_INTERFACE.")


def write_overlay(repo: Path) -> None:
    overlay_path = repo / "platformio.local.ini"
    if overlay_path.exists():
        current = overlay_path.read_text(encoding="utf-8-sig")
        if current != OVERLAY:
            raise RuntimeError(
                f"Refusing to overwrite an existing custom config: {overlay_path}\n"
                "Use a clean --work-dir or back up your own config first."
            )
        print("Using existing generated overlay.")
        return
    overlay_path.write_text(OVERLAY, encoding="utf-8", newline="\n")
    print(f"Created: {overlay_path}")


def ensure_platformio(no_install: bool) -> None:
    if importlib.util.find_spec("platformio") is None:
        if no_install:
            raise RuntimeError("PlatformIO missing. Install: python -m pip install platformio==6.2.0")
        run(sys.executable, "-m", "pip", "install", "platformio==6.2.0")
    run(sys.executable, "-m", "platformio", "--version")


def get_checkout(repo: Path, ref: str) -> str:
    if not repo.exists():
        repo.parent.mkdir(parents=True, exist_ok=True)
        run("git", "clone", "--depth", "1", "--branch", ref, UPSTREAM_URL, str(repo))
    if not (repo / ".git").exists():
        raise RuntimeError(f"Existing directory is not a Git checkout: {repo}")
    origin = output("git", "remote", "get-url", "origin", cwd=repo)
    if origin.rstrip("/").removesuffix(".git") != UPSTREAM_URL.removesuffix(".git"):
        raise RuntimeError(f"Unexpected Git origin {origin}; refusing to use it.")
    commit = output("git", "rev-parse", "HEAD", cwd=repo)
    if ref == DEFAULT_REF and not commit.startswith(TESTED_COMMIT_PREFIX):
        raise RuntimeError(f"Unexpected commit for {ref}: {commit}; expected {TESTED_COMMIT_PREFIX}...")
    if ref != DEFAULT_REF:
        print(f"WARNING: {ref} is not the hardware-tested release; check changes carefully.")
    # Do not fetch, reset, or clobber changes in a checked-out tree.
    return commit


def checksum(path: Path) -> str:
    h = hashlib.sha256()
    with path.open("rb") as inp:
        for block in iter(lambda: inp.read(1024 * 1024), b""):
            h.update(block)
    return h.hexdigest()


def build(args: argparse.Namespace) -> None:
    if shutil.which("git") is None:
        raise RuntimeError("Git is missing. Install Git for Windows or your OS package manager.")
    ref = safe_ref(args.ref)
    work_dir = Path(args.work_dir).expanduser().resolve()
    repo = work_dir / f"MeshCore-{ref}"
    out_dir = Path(args.output_dir).expanduser().resolve()
    print(f"Source tag: {ref}\nWork area : {repo}\nOutput dir: {out_dir}")
    commit = get_checkout(repo, ref)
    validate_upstream(repo)
    write_overlay(repo)
    ensure_platformio(args.no_install)

    run(sys.executable, "-m", "platformio", "run", "-e", ENVIRONMENT, cwd=repo)
    build_dir = repo / ".pio" / "build" / ENVIRONMENT
    app = build_dir / "firmware.bin"
    if not app.is_file() or app.stat().st_size < 1024:
        raise RuntimeError("Build finished without a valid application firmware.bin")

    merged = build_dir / "firmware-merged.bin"
    if not args.skip_merged:
        run(sys.executable, "-m", "platformio", "run", "-e", ENVIRONMENT, "-t", "mergebin", cwd=repo)
        if not merged.is_file() or merged.stat().st_size < app.stat().st_size:
            raise RuntimeError("Merged firmware was not generated; refusing to ship an incomplete image.")

    out_dir.mkdir(parents=True, exist_ok=True)
    artifacts = {"application": app}
    if not args.skip_merged:
        artifacts["merged"] = merged
    names = {
        "application": f"TBeam_SX1276_USB_{ref}_app-0x10000.bin",
        "merged": f"TBeam_SX1276_USB_{ref}_merged-0x0.bin",
    }
    hashes = {}
    for kind, src in artifacts.items():
        dest = out_dir / names[kind]
        shutil.copy2(src, dest)
        hashes[dest.name] = checksum(dest)
        print(f"Firmware created: {dest} ({dest.stat().st_size:,} bytes)")

    manifest = {
        "project": "meshcore-tbeam-sx1276-usb",
        "upstream": UPSTREAM_URL,
        "upstream_ref": ref,
        "upstream_commit": commit,
        "build_environment": ENVIRONMENT,
        "hardware": "LilyGO TTGO T-Beam ESP32 + SX1276 (T22 V1.x candidates)",
        "transport": "USB serial / CP210x",
        "generated_utc": datetime.now(timezone.utc).isoformat(),
        "files_sha256": hashes,
        "note": "Community build, not an official MeshCore release. Flashing erases/replaces software.",
    }
    (out_dir / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n", encoding="utf-8")
    (out_dir / "SHA256SUMS.txt").write_text("".join(f"{h}  {name}\n" for name, h in hashes.items()), encoding="ascii")
    print("\nSUCCESS — firmware is available in:", out_dir)
    print("Merged image: 0x0. App-only image: 0x10000 (existing compatible partition layout ONLY).")
    print("WARNING: Hardware functionality must be verified after flashing.")


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", default=DEFAULT_REF, help="Upstream MeshCore release tag")
    parser.add_argument("--work-dir", default=str(PROJECT_DIR / ".work"))
    parser.add_argument("--output-dir", default=str(PROJECT_DIR / "dist"))
    parser.add_argument("--no-install", action="store_true", help="Do not auto-install PlatformIO")
    parser.add_argument("--skip-merged", action="store_true", help="Only build app image; not suitable for first flash")
    args = parser.parse_args()
    try:
        build(args)
    except (RuntimeError, OSError, subprocess.CalledProcessError, ValueError) as exc:
        print(f"\nBUILD FAILED: {exc}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
